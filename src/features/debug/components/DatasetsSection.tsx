import { t } from '../../../locales/ui.ts';
import { formatBytes, formatDuration } from '../../../shared/lib/format.ts';
import type { DatasetLoadReport } from '../../../shared/lib/fetch-dataset.ts';
import { DataTable } from '../../../shared/ui/DataTable.tsx';
import { Section } from '../../../shared/ui/Section.tsx';

interface DatasetsSectionProps {
  readonly id: string;
  readonly reports: readonly DatasetLoadReport[];
}

export function DatasetsSection({ id, reports }: DatasetsSectionProps) {
  return (
    <Section
      id={id}
      title={t('Dataset files')}
      description={t(
        'Generated by `npm run data` from pinned raw sources. Sizes are uncompressed; static hosts serve them gzip-compressed.',
      )}
    >
      <DataTable
        rows={reports}
        rowKey={(report) => report.path}
        columns={[
          { header: t('File'), render: (report) => <code>{report.path}</code> },
          { header: t('Size'), align: 'end', render: (report) => formatBytes(report.bytes) },
          {
            header: t('Download'),
            align: 'end',
            render: (report) => formatDuration(report.downloadMs),
          },
          { header: t('Parse'), align: 'end', render: (report) => formatDuration(report.parseMs) },
          {
            header: t('Validate & index'),
            align: 'end',
            render: (report) => formatDuration(report.processMs),
          },
        ]}
      />
    </Section>
  );
}
